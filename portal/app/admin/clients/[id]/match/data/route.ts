import ExcelJS from "exceljs";
import { NextResponse } from "next/server";
import { getAuthContext } from "@/lib/auth";
import { isServiceRoleConfigured } from "@/lib/env";
import { createServiceClient } from "@/lib/supabase/admin";
import { matchDataHeader, matchDataRows } from "@/lib/match/tiers/match-data";
import { RULES_VERSION } from "@/lib/match/tiers/core";
import { matchDataSnapshot } from "@/lib/match/tiers/server";

// "Download match data": what a match for this client reads right now. The
// corrected live Fund Database with each fund's raw values and taxonomy
// categories, the taxonomy revision and the client's profile. Runs nothing,
// saves nothing. Admin only.
export const dynamic = "force-dynamic";
export const maxDuration = 120;

const UUID = /^[0-9a-f-]{36}$/i;

type Named = { id: string | null; label: string | null } | null | undefined;
const named = (value: unknown) => {
  const v = value as Named;
  return v?.id ? `${v.label ?? v.id} (${v.id})` : "";
};
const namedList = (value: unknown) => ((value as Named[]) ?? []).map(named).filter(Boolean).join("; ");

export async function GET(_request: Request, { params }: { params: { id: string } }) {
  const { user, role } = await getAuthContext();
  if (!user || role !== "admin") return NextResponse.json({ error: "Unauthorized." }, { status: 401 });
  if (!isServiceRoleConfigured()) return NextResponse.json({ error: "Service role key is not configured." }, { status: 500 });
  if (!UUID.test(params.id)) return NextResponse.json({ error: "Unknown client." }, { status: 400 });

  const snapshot = await matchDataSnapshot(createServiceClient(), params.id);
  if (!snapshot.ok) return NextResponse.json({ error: snapshot.error }, { status: 400 });
  const { db, index, common, profileInputs: p, exclusions, suppressed, corrections } = snapshot.value;
  const generated = new Date().toISOString();

  const book = new ExcelJS.Workbook();

  const about = book.addWorksheet("About");
  about.columns = [{ width: 32 }, { width: 90 }];
  about.addRows([
    ["Client", String(common.client_name ?? "")],
    ["Client ID", params.id],
    ["Generated", generated],
    ["Generated by", user.email ?? ""],
    ["Fund Database version", String(common.fund_db_version ?? "")],
    ["Fund Database file", String(common.fund_db_file ?? "")],
    ["Fund Database rows", db.firms.length],
    ["Data corrections applied", corrections],
    ["Taxonomy revision", Number(common.taxonomy_revision ?? 0)],
    ["Profile version", common.profile_version == null ? "legacy (no version)" : Number(common.profile_version)],
    ["Engine rules version", RULES_VERSION],
    ["Note", "Read only: nothing was run or saved. Categories come from the same mapping the match engine uses."],
  ]);
  about.getColumn(1).font = { bold: true };

  const profile = book.addWorksheet("Profile");
  profile.columns = [{ width: 32 }, { width: 90 }];
  profile.addRows([
    ["Primary sector", named(p.primarySector)],
    ["Secondary sectors (in profile order)", namedList(p.secondarySectors)],
    ["Stage", named(p.stage)],
    ["Stage reach", String(p.stageReach ?? "exact")],
    ["HQ country", named(p.hqCountry)],
    ["HQ state", named(p.hqState)],
    ["Financing (blank = Equity)", namedList(p.financing)],
    ["Firm types (blank = stage defaults)", namedList(p.firmTypes)],
    ["Readiness", String(p.readiness ?? "")],
    ["Unconfirmed", namedList(p.unconfirmed)],
    ["Warnings", ((p.warnings as string[]) ?? []).join("\n")],
    ["Exclusions (as the engine reads them)", exclusions],
    ["Funds hidden for all clients", Object.keys(suppressed).length],
  ]);
  profile.getColumn(1).font = { bold: true };
  profile.getColumn(2).alignment = { wrapText: true, vertical: "top" };

  const funds = book.addWorksheet("Funds", { views: [{ state: "frozen", ySplit: 1, xSplit: 3 }] });
  funds.addRow(matchDataHeader());
  funds.addRows(matchDataRows(db, index, suppressed));
  funds.getRow(1).font = { bold: true };

  const slug = String(common.client_name ?? "client").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "client";
  const buffer = await book.xlsx.writeBuffer();
  return new NextResponse(Buffer.from(buffer), {
    headers: {
      "Content-Type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      "Content-Disposition": `attachment; filename="rupert-match-data-${slug}-r${common.taxonomy_revision}-${generated.slice(0, 10)}.xlsx"`,
      "Cache-Control": "no-store",
    },
  });
}
